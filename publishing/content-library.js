// שליפת פוסט לפי אינדקס (עם סיבוב)
function getPost(index) {
  return POSTS[index % POSTS.length];
}

// שליפת כל הפוסטים לפלטפורמה מסוימת
function getPostsForPlatform(platform) {
  return POSTS.filter(p => p.platforms.includes(platform));
}

// שליפת פוסט אקראי לפלטפורמה
function getRandomPost(platform) {
  const available = getPostsForPlatform(platform);
  return available[Math.floor(Math.random() * available.length)];
}

// מונה פוסטים שפורסמו (כדי לעבור דרך הספרייה בסדר)
let currentIndex = 0;
function getNextPost() {
  const post = POSTS[currentIndex % POSTS.length];
  currentIndex++;
  return post;
}

